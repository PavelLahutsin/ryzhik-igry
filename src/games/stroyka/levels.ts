/**
 * How the plan shows the places: `plan` — dashed places in their colours;
 * `half` — one half is built, the other half has grey places (mirror it);
 * `copy` — grey places only, the colours are on the small sample picture.
 */
export type Look = "plan" | "half" | "copy";

export type Alive = "tower" | "drive" | "train" | "house" | "rocket" | "boat";

export type Plan = LevelInfo & {
  look?: Look;
  cols: number;
  rows: number;
  pieces: Piece[];
  /** Extra blocks in the tray that are not needed (a real choice). */
  extra: Pick<Piece, "kind" | "color" | "w" | "h">[];
  alive: Alive;
  /**
   * Someone who belongs in the finished model (climbs it, walks over it,
   * sails on it, comes to the door). Feet at (x, y) in grid cells, `h` rows
   * tall; `walk` = goes across to `x2`; `ground` = stands outside the model.
   */
  guest?: { id: string; x: number; y: number; h: number; x2?: number; ground?: boolean };
  intro: string;
  done: string;
};

const p = (kind: Kind, color: ColorId, x: number, y: number, w = 1, h = 1, more: Partial<Piece> = {}): Piece => ({ kind, color, x, y, w, h, ...more });

